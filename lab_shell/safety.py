"""Conservative execution allowlist; deliberately not a shell security sandbox."""

import re
import shlex
from dataclasses import dataclass


@dataclass(frozen=True)
class Assessment:
    executable: bool
    label: str
    reason: str
    argv: tuple[str, ...] = ()


def assess(command: str) -> Assessment:
    def deny(reason: str) -> Assessment:
        return Assessment(False, "需人工审核", reason)

    if not command.strip():
        return deny("没有可执行命令。")
    if re.search(r"[\x00-\x1f\x7f|;&<>`$(){}]", command):
        return deny("包含组合、重定向、替换或控制字符，只提供预览。")
    try:
        argv = shlex.split(command)
    except ValueError:
        return deny("引号不匹配。")
    if not argv:
        return deny("没有可执行命令。")
    name, *args = argv
    # Allow only well-understood argument grammars. No interpreter, sudo or PATH syntax.
    safe = False
    if name in {"pwd", "whoami", "who", "uptime", "hostname", "date", "id"}:
        safe = not args
    elif name in {"df", "free", "uname", "ls", "ps", "ss", "du"}:
        patterns = {
            "df": r"-[hHTiklmPa]+", "free": r"-[hbkmgtw]+", "uname": r"-[asnrvmpio]+",
            "ls": r"-[lahdRSt1]+", "ps": r"aux|-[ef]+", "ss": r"-[tulnap46]+",
            "du": r"-[shakm]+",
        }
        safe = all(re.fullmatch(patterns[name], arg) or (name == "du" and arg == ".") for arg in args)
        # ss's port filter has its own narrow grammar.
        if name == "ss" and args and re.fullmatch(r"sport = :\d{1,5}", args[-1]):
            port = int(args[-1].split(":")[-1])
            safe = 1 <= port <= 65535 and all(re.fullmatch(patterns[name], a) for a in args[:-1])
    elif name == "ip":
        safe = args in (["-brief", "address", "show"], ["address", "show"], ["route", "show"], ["link", "show"])
    elif name == "cat":
        safe = args == ["/etc/os-release"]
    elif name == "find":
        # Exactly the grammar generated by the local knowledge base.
        safe = (
            len(args) == 5 and not args[0].startswith("-")
            and args[1:3] == ["-type", "f"]
            and (args[3] == "-name" or (args[3] == "-size" and bool(re.fullmatch(r"\+[1-9]\d*[kMG]", args[4]))))
        )
    elif name == "tail":
        safe = len(args) == 4 and args[0] == "-n" and bool(re.fullmatch(r"[1-9]\d{0,4}", args[1])) and args[2] == "--"
    elif name == "grep":
        safe = len(args) == 4 and args[:2] == ["-nF", "--"]
    if not safe:
        return deny("不符合内置只读命令及参数白名单；请阅读后在终端手动操作。")
    return Assessment(True, "只读白名单", "仍需人工确认；可能读取敏感内容或消耗系统资源。", tuple(argv))
